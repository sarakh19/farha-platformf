/*
|--------------------------------------------------------------------------
| مساعد عرض الرسائل
|--------------------------------------------------------------------------
| مثال:
| showMsg('register', 'success');
*/

window.showMsg = function (page, key) {
    const pageMessages = window.FARHA_MESSAGES[page];
    const entry = pageMessages && pageMessages[key];

    if (!entry) {
        console.warn(
            'Farha message not found:',
            page,
            key
        );

        return;
    }

    /*
     * رسائل التأكيد لا تظهر كـ Toast،
     * بل ترجع كنص لاستخدامها مع confirm().
     */
    if (entry.type === 'confirm') {
        return entry.text;
    }

    if (typeof window.showToast === 'function') {
        window.showToast(entry.text, entry.type);
    } else {
        console.warn(
            'showToast function is not available.'
        );
    }
};